"""W7-T4 (D3): one audit event per staff request that exposes student data.

The requirement is deliberately *request-level*, not row-level: a counselor paginating through
200 leads produces one event, not 200. What matters is that somebody looked, and who.

Every event records exactly the five things D3 asks for and nothing else:

===========  ==============================================================
Actor        ``actor_id`` + ``actor_email`` from the authenticated staff user
Resource     ``entity_type`` - a constant from the allowlists below
Operation    ``action`` ("READ") + ``detail.operation`` (list/detail/queue/...)
Time         ``created_at``, server-generated by the column default
Relevant ID  ``entity_id`` - the row or student the request targeted, if any
===========  ==============================================================

It must never record student names, emails, phone numbers, message bodies, document contents or
storage URLs, request/response bodies, credentials, query strings or arbitrary user input. The
only values written are constants defined in this module plus integers taken from the route, so a
caller cannot influence the event's content.

The allowlists are the guard against accidental caller-controlled values: passing a resource name
that is not on them is a programming error and raises, so a new route cannot quietly invent an
audit label from a path segment.

Fail closed. ``audit_student_read`` commits before the handler returns its data, and raises
:class:`AuditUnavailable` if that commit fails. A protected response must not escape unaudited;
the route turns the exception into a 503.
"""
from __future__ import annotations

import logging
from typing import Optional

from sqlalchemy.orm import Session

from app.models.crm import AuditLog, User

log = logging.getLogger(__name__)

#: Generic-CRUD resource keys whose rows are student data (see ``admin.RESOURCES``).
STUDENT_DATA_RESOURCES = frozenset({
    "leads",
    "appointments",
    "student-profiles",
    "applications",
    "application-history",
    "documents",
    "brochures",
    "notifications",
    "shortlist-items",
    "assistant-conversations",
    "event-registrations",
})

#: Every ``entity_type`` this module is allowed to write. Resource keys plus the named staff
#: surfaces that expose student data without mapping to a single resource.
AUDITED_SURFACES = STUDENT_DATA_RESOURCES | frozenset({
    "dashboard",
    "counselor-dashboard",
    # Session metadata links an assistant session to a profile identifier, an ownership state and
    # activity timestamps. No name, email or phone, but it is student-linked information a member
    # of staff can only see by asking for it, so it is audited like the rest of the surface.
    "assistant-sessions",
})

#: ``detail.operation`` values, one per call site. Constants, never caller input.
OPERATIONS = frozenset({
    "list",
    "detail",
    "dashboard",
    "board",
    "queue",
    "inbox",
    "read",
})

ACTION = "READ"


class AuditUnavailable(RuntimeError):
    """The read could not be audited, so the read must not be served."""


def is_student_resource(resource: str) -> bool:
    return resource in STUDENT_DATA_RESOURCES


def audit_student_read(
    db: Session,
    user: User,
    *,
    resource: str,
    operation: str,
    subject_id: Optional[int] = None,
) -> None:
    """Record one successful staff read of student data.

    ``resource`` and ``operation`` are validated against the constants above, so a
    caller - or anything derived from the URL - cannot set the persisted values.
    """
    if resource not in AUDITED_SURFACES:
        raise ValueError(f"{resource!r} is not an auditable student-data surface")
    if operation not in OPERATIONS:
        raise ValueError(f"{operation!r} is not a known read operation")

    db.add(AuditLog(actor_id=user.id, actor_email=user.email, action=ACTION,
                    entity_type=resource, entity_id=subject_id,
                    detail={"operation": operation}))
    try:
        # Committed here, before the handler builds its response: the alternative is a row that
        # is discarded when the request-scoped session closes, which would silently audit nothing.
        db.commit()
    except Exception as exc:  # database down, disk full, constraint change...
        db.rollback()
        log.exception("read-audit write failed for %s/%s", resource, operation)
        raise AuditUnavailable("the access could not be recorded") from exc
