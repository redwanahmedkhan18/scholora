"use client";

/**
 * shadcn/ui-style primitives: Radix behaviour + CVA variants + the `cn` merger.
 *
 * These are owned source files, not a dependency - which is the whole point of the shadcn
 * approach. Radix supplies the accessibility contract (focus trapping, ARIA wiring, keyboard
 * navigation, portalling) that the previous hand-rolled kit did not have.
 */

